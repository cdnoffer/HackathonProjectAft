import {
  Clock,
  FlaskConical,
  MapPin,
  Sunrise,
  Sunset,
  Waves,
} from "lucide-react";
import type { Scenario } from "../../shared/types";
import {
  PHASE_LABELS,
  ROAD_STATE_LABELS,
  TRAFFIC_LABELS,
  WEATHER_LABELS,
} from "../../shared/labels";
import { WeatherIcon, WeatherStat } from "./WeatherIcon";

export default function ScenarioSummary({
  scenario,
}: {
  scenario: Scenario;
}) {
  return (
    <section className="scenario-card">
      <div className="scenario-top">
        <div className="scenario-place">
          <span className="scenario-pin">
            <MapPin size={17} />
          </span>
          <div>
            <h2>{scenario.cityName}</h2>
            <span>{scenario.country}</span>
          </div>
        </div>
        <span className="simulated-pill" title="All conditions are generated by Routey">
          <FlaskConical size={12} />
          Simulated
        </span>
      </div>

      <div className="scenario-time-row">
        <span>
          <Clock size={13} />
          {scenario.simulatedAtLocal}
        </span>
        <span className="seed-label" title={`Scenario seed ${scenario.seed}`}>
          seed {scenario.seed.slice(0, 8)}
        </span>
      </div>

      <div className="weather-hero">
        <span className={`weather-hero-icon ${scenario.weather.phase}`}>
          <WeatherIcon
            condition={scenario.weather.condition}
            phase={scenario.weather.phase}
            size={30}
          />
        </span>
        <div className="weather-hero-main">
          <strong>{Math.round(scenario.weather.temperatureC)}°C</strong>
          <span>
            {WEATHER_LABELS[scenario.weather.condition]} · feels{" "}
            {Math.round(scenario.weather.feelsLikeC)}°
          </span>
        </div>
        <div className="weather-badges">
          <span className={`road-state road-state-${scenario.weather.roadState}`}>
            <Waves size={12} />
            {ROAD_STATE_LABELS[scenario.weather.roadState]}
          </span>
          <span className="phase-chip">{PHASE_LABELS[scenario.weather.phase]}</span>
        </div>
      </div>

      <div className="weather-grid">
        <WeatherStat
          icon="eye"
          label="Visibility"
          value={`${scenario.weather.visibilityKm} km`}
        />
        <WeatherStat
          icon="wind"
          label="Wind"
          value={`${scenario.weather.windKph} km/h`}
        />
        <WeatherStat
          icon="humidity"
          label="Humidity"
          value={`${scenario.weather.humidityPct}%`}
        />
        <WeatherStat
          icon="temp"
          label="Ice risk"
          value={`${scenario.weather.iceRisk}/100`}
        />
      </div>

      <div className="scenario-footer-row">
        <span className="traffic-chip">
          <span className={`traffic-dot traffic-${scenario.traffic.level}`} />
          {TRAFFIC_LABELS[scenario.traffic.level]} · {scenario.traffic.congestionPct}%
        </span>
        {scenario.weather.sunriseLocal && scenario.weather.sunsetLocal ? (
          <span className="sun-row">
            <Sunrise size={13} /> {scenario.weather.sunriseLocal}
            <Sunset size={13} /> {scenario.weather.sunsetLocal}
          </span>
        ) : null}
      </div>
    </section>
  );
}
